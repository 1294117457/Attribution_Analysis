--
-- S5: raw_data 库 —— 三张「语义错配」表按 **Tushare 真实接口** 重建
--
-- 背景（Step 3 / 方案 A）：
--   这三张表的远端结构与本地 ORM 讲的不是一回事，且**本地 ORM 的字段在 Tushare 上游根本不存在**：
--
--   ① capital_hsgt_top10
--      远端 = Tushare `hsgt_top10` 官方结构（每日沪深股通**成交金额**排名前10的股票）
--      本地 ORM = 「持仓天数 / 持股占比 / 持仓市值」→ 上游无此字段 → 永远写 NULL
--      ❗ 真实上游列（2025-10-29 实测）：
--         trade_date, ts_code, name, close, change, rank, market_type,
--         amount, net_amount, buy, sell
--      → 本地 ORM 的 holding_days / share_ratio / hold_amount 三个字段**必须删**
--
--   ② capital_moneyflow_hsgt
--      远端 = 「按股票的**成交排行**」（有 symbol / rank / close / buy / sell）
--      本地 ORM = 「按**交易所**的资金净流入汇总」（exchange / buy_amount / sell_amount）
--      ❗ 真实上游列（2025-10-29 实测）：
--         trade_date, ggt_ss, ggt_sz, hgt, sgt, north_money, south_money
--         —— 是**单行/交易日的资金流汇总**，**根本没有 symbol / rank / buy / sell**
--      → 远端表结构**完全错误**（照着 hsgt_top10 抄的），必须按上游重建
--
--   ③ capital_limit_list_d
--      远端 = Tushare `limit_list_d` 官方结构（close / pct_chg / limit_amount /
--             float_mv / total_mv / turnover_ratio / fd_amount / first_time /
--             last_time / open_times / up_stat / limit_times / limit_type / industry）
--      本地 ORM = close_price / change_rate / board_count / first_limit_time /
--             board_strength / reason → 大半字段上游无 → 永远 NULL
--
-- 决策（方案 A）：**改本地 ORM 去迁就远端 / 上游**，不迁就本地 ORM。
--   理由：远端表 = Tushare 官方结构 = 唯一真实数据源；
--        本地 ORM 那套字段是早期凭想象设计的，上游压根不提供。
--   ⚠️ 本次实测：**当前 TUSHARE_TOKEN 无 `limit_list_d` 接口权限**
--      （上游报「您没有接口(limit_list_d)访问权限」）
--      → 该表结构仍按官方文档对齐，但采集会因权限失败，属**账号权限问题**，非结构问题。
--
-- ⚠️ 三张表**当前均为 0 行**（实测），重建零数据风险。
--    旧表已备份：backup-raw-data-hsgt-limit.sql
--
-- 执行：psql -h 8.148.204.54 -U zhouch -d raw_data -f 05-rebuild-hsgt-limit-tables.sql
--

BEGIN;

-- ═══════════════════════════════════════════════════════════════════════
-- ① capital_hsgt_top10：Tushare hsgt_top10 官方结构
--    删掉本地 ORM 自造的 holding_days / share_ratio / hold_amount
-- ═══════════════════════════════════════════════════════════════════════
ALTER TABLE public.capital_hsgt_top10
    DROP COLUMN IF EXISTS holding_days,
    DROP COLUMN IF EXISTS share_ratio,
    DROP COLUMN IF EXISTS hold_amount;

-- 上游列名是 `change`，远端列名是 `p_change` → 统一改名到上游名
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
                WHERE table_schema='public' AND table_name='capital_hsgt_top10'
                  AND column_name='p_change')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
                WHERE table_schema='public' AND table_name='capital_hsgt_top10'
                  AND column_name='change')
    THEN
        EXECUTE 'ALTER TABLE public.capital_hsgt_top10 RENAME COLUMN p_change TO change';
        RAISE NOTICE 'capital_hsgt_top10.p_change → change';
    END IF;
END $$;

COMMENT ON TABLE public.capital_hsgt_top10 IS
    '沪深股通每日十大成交股（Tushare hsgt_top10 官方结构）';
COMMENT ON COLUMN public.capital_hsgt_top10.rank IS '资金排名（1-10）';
COMMENT ON COLUMN public.capital_hsgt_top10.market_type IS '市场类型（1=沪市 3=深市）';
COMMENT ON COLUMN public.capital_hsgt_top10.amount IS '成交金额（元）';
COMMENT ON COLUMN public.capital_hsgt_top10.net_amount IS '净成交金额（元）';
COMMENT ON COLUMN public.capital_hsgt_top10.buy IS '买入金额（元）';
COMMENT ON COLUMN public.capital_hsgt_top10.sell IS '卖出金额（元）';
COMMENT ON COLUMN public.capital_hsgt_top10.change IS '涨跌额';

-- ═══════════════════════════════════════════════════════════════════════
-- ② capital_moneyflow_hsgt：Tushare moneyflow_hsgt 官方结构
--    ★ 结构彻底重写：远端原本照抄了 hsgt_top10（按股票排行），
--      但上游实际是「按交易日的资金流汇总」，单行一天。
--    ★ 因为结构完全变了 → 必须重建表（ALTER 改不动）。
-- ═══════════════════════════════════════════════════════════════════════
DROP TABLE IF EXISTS public.capital_moneyflow_hsgt;

CREATE TABLE public.capital_moneyflow_hsgt (
    id           integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_date   date         NOT NULL,
    -- 港股通（南向）
    ggt_ss       double precision,   -- 港股通（上海）
    ggt_sz       double precision,   -- 港股通（深圳）
    -- 陆股通（北向）
    hgt          double precision,   -- 沪股通
    sgt          double precision,   -- 深股通
    north_money  double precision,   -- 北向资金（百万元）
    south_money  double precision,   -- 南向资金（百万元）
    data_source  character varying(16) NOT NULL DEFAULT 'tushare',
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_capital_moneyflow_hsgt_uk UNIQUE (trade_date)
);

COMMENT ON TABLE public.capital_moneyflow_hsgt IS
    '沪深港通资金流向（Tushare moneyflow_hsgt 官方结构：一行=一个交易日的资金流汇总）';
COMMENT ON COLUMN public.capital_moneyflow_hsgt.north_money IS '北向资金（百万元）';
COMMENT ON COLUMN public.capital_moneyflow_hsgt.south_money IS '南向资金（百万元）';
COMMENT ON COLUMN public.capital_moneyflow_hsgt.ggt_ss IS '港股通（上海）成交金额（百万元）';
COMMENT ON COLUMN public.capital_moneyflow_hsgt.ggt_sz IS '港股通（深圳）成交金额（百万元）';

CREATE INDEX IF NOT EXISTS ix_capital_moneyflow_hsgt_trade_date
    ON public.capital_moneyflow_hsgt (trade_date);

-- ═══════════════════════════════════════════════════════════════════════
-- ③ capital_limit_list_d：Tushare limit_list_d 官方结构
--    删掉本地 ORM 自造的 close_price / change_rate / board_count /
--    first_limit_time / board_strength / reason
-- ═══════════════════════════════════════════════════════════════════════
ALTER TABLE public.capital_limit_list_d
    DROP COLUMN IF EXISTS close_price,
    DROP COLUMN IF EXISTS change_rate,
    DROP COLUMN IF EXISTS board_count,
    DROP COLUMN IF EXISTS first_limit_time,
    DROP COLUMN IF EXISTS board_strength,
    DROP COLUMN IF EXISTS reason;

COMMENT ON TABLE public.capital_limit_list_d IS
    '每日涨跌停板（Tushare limit_list_d 官方结构）';
COMMENT ON COLUMN public.capital_limit_list_d.limit_type IS '涨跌停类型（U涨停 D跌停 Z炸板）';
COMMENT ON COLUMN public.capital_limit_list_d.limit_times IS '连板数';
COMMENT ON COLUMN public.capital_limit_list_d.open_times IS '炸板次数';
COMMENT ON COLUMN public.capital_limit_list_d.up_stat IS '涨停统计（N/T T天有N次涨停）';
COMMENT ON COLUMN public.capital_limit_list_d.fd_amount IS '封单金额';
COMMENT ON COLUMN public.capital_limit_list_d.limit_amount IS '板上成交金额';

COMMIT;

