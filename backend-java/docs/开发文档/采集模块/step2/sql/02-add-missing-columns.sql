--
-- S2: raw_data 库 —— 补齐缺失列
--
-- 背景：本地 ORM 声明的列与远端表列集合不一致，需 ADD 缺失列（全部 nullable，不动已有数据）。
--
-- ① fundamental_stock_basic：ORM 有 total_shares（股本），远端无 → 补
-- ② 三张「语义不同」的表：远端存的是 Tushare 每日排行榜结构，本地 ORM 是持仓/汇总结构
--    → 补 ORM 需要的列（nullable），保留远端原始字段（rank/close/buy/sell 等，后续业务分析有用）
--
-- 执行：psql -h 8.148.204.54 -U zhouch -d raw_data -f 02-add-missing-columns.sql
-- 可逆：DROP COLUMN 即可（不影响已有数据）。
--

BEGIN;

-- ═══════════════════════════════════════════════════════════════════════
-- ① fundamental_stock_basic：补 total_shares
-- ═══════════════════════════════════════════════════════════════════════
ALTER TABLE public.fundamental_stock_basic
    ADD COLUMN IF NOT EXISTS total_shares bigint;

COMMENT ON COLUMN public.fundamental_stock_basic.total_shares IS '总股本（股）';

-- ═══════════════════════════════════════════════════════════════════════
-- ② capital_hsgt_top10
--    远端存「沪深港通每日十大成交股排行」；本地 ORM 期望「持仓天数/占比/市值」
-- ═══════════════════════════════════════════════════════════════════════
ALTER TABLE public.capital_hsgt_top10
    ADD COLUMN IF NOT EXISTS holding_days integer,
    ADD COLUMN IF NOT EXISTS share_ratio double precision,
    ADD COLUMN IF NOT EXISTS hold_amount double precision;

-- ═══════════════════════════════════════════════════════════════════════
-- ③ capital_moneyflow_hsgt
--    远端存「每日十大成交股排行」；本地 ORM 期望「交易所维度买/卖/净额」
-- ═══════════════════════════════════════════════════════════════════════
ALTER TABLE public.capital_moneyflow_hsgt
    ADD COLUMN IF NOT EXISTS exchange character varying(8),
    ADD COLUMN IF NOT EXISTS buy_amount double precision,
    ADD COLUMN IF NOT EXISTS sell_amount double precision;

-- ═══════════════════════════════════════════════════════════════════════
-- ④ capital_limit_list_d
--    远端存 Tushare limit_list_d 结构（close/pct_chg/limit_amount/...）；
--    本地 ORM 期望 close_price/change_rate/board_count/first_limit_time/...
-- ═══════════════════════════════════════════════════════════════════════
ALTER TABLE public.capital_limit_list_d
    ADD COLUMN IF NOT EXISTS close_price double precision,
    ADD COLUMN IF NOT EXISTS change_rate double precision,
    ADD COLUMN IF NOT EXISTS board_count integer,
    ADD COLUMN IF NOT EXISTS first_limit_time time,
    ADD COLUMN IF NOT EXISTS board_strength double precision,
    ADD COLUMN IF NOT EXISTS reason text;

-- ═══════════════════════════════════════════════════════════════════════
-- ⑤ fundamental_market_daily：本地 ORM 有、远端完全没有 → 建表
--    （对齐远端已有的 fundamental_index_daily 结构）
-- ═══════════════════════════════════════════════════════════════════════
CREATE TABLE IF NOT EXISTS public.fundamental_market_daily (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market      character varying(16) NOT NULL,
    trade_date  date         NOT NULL,
    close       double precision,
    open        double precision,
    high        double precision,
    low         double precision,
    pre_close   double precision,
    change      double precision,
    pct_chg     double precision,
    vol         double precision,
    amount      double precision,
    data_source character varying(16) NOT NULL DEFAULT 'tushare',
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_fundamental_market_daily_uk UNIQUE (market, trade_date)
);

COMMENT ON TABLE public.fundamental_market_daily IS '市场大盘日线（market= SSE/SZSE/CSI）';
COMMENT ON COLUMN public.fundamental_market_daily.market IS '市场代码: SSE/SZSE/CSI';

CREATE INDEX IF NOT EXISTS ix_fundamental_market_daily_trade_date
    ON public.fundamental_market_daily (trade_date);

COMMIT;

